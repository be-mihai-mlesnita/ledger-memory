def test_store_identity_is_private_metadata_only(tmp_path, monkeypatch):
    store = tmp_path.resolve()
    database = store / "memory.db"
    database.write_bytes(b"not even a SQLite database")
    database.chmod(0o600)
    info = database.stat()
    original_open = os.open
    def directories_only(path, flags, *args, **kwargs):
        assert flags & os.O_DIRECTORY, "identity helper opened database contents"
        return original_open(path, flags, *args, **kwargs)
