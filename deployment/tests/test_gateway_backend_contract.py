def test_store_session_only_creates_rc3_lock_and_imports_no_runtime(tmp_path):
    store = tmp_path.resolve()
    script = '''
import os, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
import gateway_backend_contract as contract
store = Path(sys.argv[2])
with contract.store_session(store):
    assert "ledger_memory.api" not in sys.modules
    assert "ledger_memory.reader" not in sys.modules
    assert "ledger_memory.db" not in sys.modules
    assert [p.name for p in store.iterdir()] == [".ledger.sessions.lock"]
    assert (store / ".ledger.sessions.lock").stat().st_mode & 0o777 == 0o600
'''
    result = subprocess.run([sys.executable, "-I", "-B", "-c", script,
                             str(Path(contract.__file__).parent), str(store)], capture_output=True, text=True, timeout=30)
    assert result.returncode == 0, result.stderr


def _exclusive_session_probe(store, queue):
    from ledger_memory import locking
    try:
        with locking.exclusive(locking.session_lock_path(Path(store) / "memory.db"), timeout=0):
            queue.put("acquired")
    except TimeoutError:
        queue.put("blocked")


def test_store_shared_leases_nest_and_block_exclusive_restore_process(tmp_path):
    store = tmp_path.resolve()
    ctx = multiprocessing.get_context("spawn")
    queue = ctx.Queue()
    with contract.store_session(store):
        with contract.store_session(store):
            child = ctx.Process(target=_exclusive_session_probe, args=(str(store), queue))
            child.start()
            assert queue.get(timeout=10) == "blocked"
            child.join(timeout=10)
            assert child.exitcode == 0
        child = ctx.Process(target=_exclusive_session_probe, args=(str(store), queue))
        child.start()
        assert queue.get(timeout=10) == "blocked"
        child.join(timeout=10)
        assert child.exitcode == 0
    child = ctx.Process(target=_exclusive_session_probe, args=(str(store), queue))
    child.start()
    assert queue.get(timeout=10) == "acquired"
    child.join(timeout=10)
    assert child.exitcode == 0


