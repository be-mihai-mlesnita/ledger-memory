@pytest.mark.parametrize("operation", PAYLOADS)
def test_all_operations_canonical_nonmutating(operation):
    payload = copy.deepcopy(PAYLOADS[operation])
    original = copy.deepcopy(payload)
    args = contract.validate_write(operation, payload)
    assert payload == original
    assert args == contract.validate_write(operation, args)
    assert contract.write_hash(operation, payload) == contract.write_hash(operation, args)
    if "fact_ids" in args:
        args["fact_ids"].append(99)
        assert payload == original


