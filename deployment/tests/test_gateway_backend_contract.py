@pytest.mark.parametrize("attack", ["symlink", "broken", "hardlink", "permissions", "parent", "fifo"])
def test_unsafe_json_files_rejected(tmp_path, attack):
    root = tmp_path.resolve()
    path, target = root / "data.json", root / "target.json"
    contract.save_json(target, {"unchanged": True})
    if attack == "symlink":
        path.symlink_to(target)
    elif attack == "broken":
        path.symlink_to(root / "missing")
    elif attack == "hardlink":
        os.link(target, path)
    elif attack == "permissions":
        contract.save_json(path, {})
        path.chmod(0o644)
    elif attack == "fifo":
        os.mkfifo(path, 0o600)
    else:
        (root / "alias").symlink_to(root, target_is_directory=True)
        path = root / "alias" / "target.json"
    for fn in (lambda: contract.load_json(path), lambda: contract.save_json(path, {})):
        with pytest.raises((ValueError, OSError)):
            fn()
    assert target.read_text() == '{"unchanged":true}'


